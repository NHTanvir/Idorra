//! Findings reports — a machine-readable JSON file (full evidence) and a
//! human-readable Markdown file for HackerOne write-ups. Secret header values
//! are already redacted in the captured evidence unless the operator opted in.

use crate::engine::RunSummary;
use crate::error::Result;
use crate::finding::Finding;
use crate::outcome::RequestOutcome;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Paths of the two report files written for a run.
#[derive(Debug, Clone)]
pub struct ReportPaths {
    /// The JSON report (full evidence).
    pub json: PathBuf,
    /// The Markdown report (human-readable).
    pub markdown: PathBuf,
}

/// Write both report files into `report_dir`, named with `run_id`.
pub fn write_reports(summary: &RunSummary, report_dir: &Path, run_id: &str) -> Result<ReportPaths> {
    std::fs::create_dir_all(report_dir)?;
    let json = report_dir.join(format!("idorra-{run_id}.json"));
    let markdown = report_dir.join(format!("idorra-{run_id}.md"));

    std::fs::write(&json, serde_json::to_string_pretty(summary)?)?;
    std::fs::write(&markdown, render_markdown(summary, run_id))?;

    Ok(ReportPaths { json, markdown })
}

/// Render the human-readable Markdown report.
pub fn render_markdown(summary: &RunSummary, run_id: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# idorra findings report — {run_id}\n");
    if summary.was_dry_run {
        let _ = writeln!(
            s,
            "> **DRY RUN** — no requests were sent. Counts below reflect what *would* be sent.\n"
        );
    }

    let _ = writeln!(s, "## Run summary\n");
    let _ = writeln!(s, "| Metric | Count |");
    let _ = writeln!(s, "| --- | ---: |");
    let _ = writeln!(s, "| Planned test cases | {} |", summary.total);
    let _ = writeln!(s, "| Sent | {} |", summary.sent);
    let _ = writeln!(s, "| Blocked (out of scope) | {} |", summary.blocked);
    let _ = writeln!(s, "| Dry-run (skipped) | {} |", summary.dry_run);
    let _ = writeln!(s, "| Network errors | {} |", summary.errored);
    let _ = writeln!(s, "| Findings | {} |\n", summary.findings.len());

    if summary.findings.is_empty() {
        let _ = writeln!(s, "## Findings\n\n_No findings were flagged._\n");
    } else {
        let _ = writeln!(s, "## Findings\n");
        for (i, f) in summary.findings.iter().enumerate() {
            render_finding(&mut s, i + 1, f);
        }
    }

    let _ = writeln!(
        s,
        "---\n\n_Generated by idorra. Findings are heuristics for manual review, not confirmed \
         vulnerabilities. Verify each before reporting._"
    );
    s
}

fn render_finding(s: &mut String, n: usize, f: &Finding) {
    let _ = writeln!(
        s,
        "### {n}. [{} / {} confidence] {}\n",
        f.severity, f.confidence, f.summary
    );
    let reasons: Vec<String> = f.reason_codes.iter().map(|r| format!("{r:?}")).collect();
    let _ = writeln!(s, "- **Strategy:** {:?}", f.strategy);
    let _ = writeln!(s, "- **Reason codes:** {}", reasons.join(", "));
    let _ = writeln!(s, "- **Sessions:** {}", f.involved_sessions.join(", "));
    let ids: Vec<String> = f.involved_ids.iter().map(|i| i.to_string()).collect();
    let _ = writeln!(s, "- **IDs:** {}", ids.join(", "));
    if !f.detected_sensitive_fields.is_empty() {
        let _ = writeln!(
            s,
            "- **Sensitive fields:** {}",
            f.detected_sensitive_fields.join(", ")
        );
    }
    if let Some(d) = &f.diff_summary {
        let _ = writeln!(
            s,
            "- **Body similarity:** {:.0}% ({} identical / {} leaves)",
            d.similarity() * 100.0,
            d.identical_leaves,
            d.total_leaves
        );
    }
    let _ = writeln!(s, "\n**Evidence:**\n");
    for o in &f.evidence {
        render_evidence(s, o);
    }
    let _ = writeln!(s);
}

fn render_evidence(s: &mut String, o: &RequestOutcome) {
    let status = o.status.map(|c| c.to_string()).unwrap_or_else(|| {
        o.error.clone().unwrap_or_else(|| "no response".to_string())
    });
    let _ = writeln!(
        s,
        "- `{}` **{} {}** → `{}`{}",
        o.session,
        o.request_evidence.method,
        o.request_evidence.url,
        status,
        o.redirect_location
            .as_ref()
            .map(|l| format!(" (Location: {l})"))
            .unwrap_or_default(),
    );
    for (k, v) in &o.request_evidence.headers {
        let _ = writeln!(s, "  - request header `{k}: {v}`");
    }
    if let Some(body) = &o.response_body {
        let snippet = snippet(body, 300);
        if !snippet.is_empty() {
            let _ = writeln!(s, "  ```\n  {}\n  ```", snippet.replace('\n', "\n  "));
        }
    }
}

fn snippet(s: &str, max: usize) -> String {
    let trimmed = s.trim();
    if trimmed.len() <= max {
        trimmed.to_string()
    } else {
        let mut end = max;
        while !trimmed.is_char_boundary(end) {
            end -= 1;
        }
        format!("{}…", &trimmed[..end])
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::finding::{Confidence, ReasonCode, Severity};
    use crate::outcome::{RequestEvidence, RequestOutcome};
    use crate::testcase::{ComparisonGroupId, IdValue, ParamLocation, Protocol, TestStrategy};
    use chrono::Utc;
    use uuid::Uuid;

    fn outcome(session: &str, status: u16) -> RequestOutcome {
        RequestOutcome {
            test_case_id: Uuid::nil(),
            target_name: "t".into(),
            session: session.into(),
            strategy: TestStrategy::TwoSessionCompare,
            param_location: ParamLocation::Path,
            id_value: IdValue::Numeric(7),
            comparison_group_id: ComparisonGroupId(Uuid::nil()),
            protocol: Protocol::Rest,
            is_baseline: session == "a",
            method: "GET".into(),
            url: "https://api.example.com/api/orders/7".into(),
            sent_at: Utc::now(),
            request_evidence: RequestEvidence {
                method: "GET".into(),
                url: "https://api.example.com/api/orders/7".into(),
                headers: vec![("Cookie".into(), "<redacted:5 chars>".into())],
                body: None,
            },
            status: Some(status),
            response_headers: vec![],
            response_body: Some("{\"email\":\"a@b.com\"}".into()),
            body_truncated: false,
            body_len: Some(18),
            elapsed_ms: 3,
            error: None,
            dry_run: false,
            redirect_location: None,
        }
    }

    fn summary_with_finding() -> RunSummary {
        let f = Finding::from_evidence(
            TestStrategy::TwoSessionCompare,
            Severity::High,
            Confidence::High,
            "Session 'b' received data 100% identical to baseline 'a' for id 7",
            vec![ReasonCode::CrossSessionDataMatch, ReasonCode::SensitiveFieldExposed],
            None,
            vec!["email".into()],
            vec![outcome("a", 200), outcome("b", 200)],
        );
        RunSummary {
            total: 2,
            sent: 2,
            blocked: 0,
            dry_run: 0,
            errored: 0,
            was_dry_run: false,
            findings: vec![f],
            outcomes: vec![outcome("a", 200), outcome("b", 200)],
        }
    }

    #[test]
    fn markdown_contains_summary_and_finding() {
        let md = render_markdown(&summary_with_finding(), "20260723-000000");
        assert!(md.contains("# idorra findings report"));
        assert!(md.contains("Planned test cases"));
        assert!(md.contains("HIGH / high confidence"));
        assert!(md.contains("Sensitive fields:"));
        assert!(md.contains("email"));
        // Secret values stay redacted in the report.
        assert!(md.contains("<redacted:5 chars>"));
    }

    #[test]
    fn dry_run_report_is_marked() {
        let mut sum = summary_with_finding();
        sum.was_dry_run = true;
        let md = render_markdown(&sum, "run");
        assert!(md.contains("DRY RUN"));
    }

    #[test]
    fn writes_both_files() {
        let dir = std::env::temp_dir().join(format!("idorra-test-{}", Uuid::new_v4()));
        let paths = write_reports(&summary_with_finding(), &dir, "run1").unwrap();
        assert!(paths.json.exists());
        assert!(paths.markdown.exists());
        let json = std::fs::read_to_string(&paths.json).unwrap();
        assert!(json.contains("\"findings\""));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
